//! `INDEX.md` in `knowledge.dir`: the accepted knowledge in one line per
//! item — ID and a short title, grouped by file and `## ` section — plus
//! the reference docs (`knowledge.extra`). An agent reads this instead of
//! the whole files, then fetches only the items its change touches
//! (`zforge knowledge get`, MCP `knowledge_get`).
//!
//! Generated, never reviewed: it is not one of [`super::FILES`], so
//! review, lint and handover pinning never see it, and editing it changes
//! nothing. Written whenever a knowledge file is accepted, by `zforge
//! onboard status` and by `zforge knowledge index` — and only when its
//! content changed, so a read-only command leaves the tree as it was.
//!
//! Each line is `- <ID>: <title>` — the same `ID:` shape the knowledge
//! files use, so a search for `DOM-004:` finds it in both — with no
//! per-line module (the `### ` heading above it carries it): on a 248 KB
//! `domain.md` the module repeated on every line alone would cost more
//! than the 10% this file aims at.

use super::items;
use super::lookup::{self, AcceptedFile};
use super::{reference, Knowledge, FILES};
use crate::config::Config;
use anyhow::Result;
use std::path::PathBuf;

pub const INDEX_FILE: &str = "INDEX.md";

/// Longest title, in characters, before it is cut at a word. 36 keeps the
/// index near a tenth of the files it indexes for items of a few hundred
/// bytes each (80 would double it); most titles end sooner, at their
/// first sentence, and the section heading above carries the module.
pub const TITLE_CHARS: usize = 36;

/// The item's first sentence, without emphasis markers, cut at a word
/// before [`TITLE_CHARS`] with `…`.
pub fn short_title(text: &str) -> String {
    let flat = text
        .replace("**", "")
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ");
    let first = match flat.find(". ") {
        Some(i) => &flat[..i],
        None => flat.trim_end_matches('.'),
    };
    if first.chars().count() <= TITLE_CHARS {
        return first.to_string();
    }
    let mut out = String::new();
    for w in first.split(' ') {
        let len = out.chars().count() + w.chars().count() + usize::from(!out.is_empty());
        if len > TITLE_CHARS {
            break;
        }
        if !out.is_empty() {
            out.push(' ');
        }
        out.push_str(w);
    }
    if out.is_empty() {
        out = first.chars().take(TITLE_CHARS).collect();
    }
    out.trim_end_matches([',', ';', ':']).to_string() + "…"
}

/// `INDEX.md`'s content from the accepted files and the reference docs.
pub fn render(accepted: &[AcceptedFile], extra: &[(String, PathBuf)]) -> String {
    let mut out = String::from(
        "# Knowledge index\n\n<!-- Generated by zforge from the accepted knowledge; editing it \
         changes nothing. -->\n\nOne line per accepted item. Read this first, then fetch only \
         the items the change touches: `zforge knowledge get <ID…>`, `--module <section|path>` \
         or `--grep <text>` (MCP `knowledge_get`).\n",
    );
    for file in FILES {
        let Some(f) = accepted.iter().find(|a| a.file == file) else {
            out.push_str(&format!("\n## {file} — not accepted yet\n"));
            continue;
        };
        let parsed = items::items(&f.text);
        out.push_str(&format!(
            "\n## {file} (rev {}, {} items)\n",
            f.revision,
            parsed.len()
        ));
        let mut section: Option<&str> = None;
        for it in &parsed {
            if section != Some(it.section.as_str()) {
                section = Some(it.section.as_str());
                if !it.section.is_empty() {
                    out.push_str(&format!("\n### {}\n\n", it.section));
                } else {
                    out.push('\n');
                }
            }
            out.push_str(&format!("- {}: {}\n", it.id, short_title(&it.text)));
        }
    }
    let refs = reference::index_section(extra);
    if !refs.is_empty() {
        out.push('\n');
        out.push_str(&refs);
    }
    out
}

/// Write `INDEX.md` when its content changed. Returns its path and
/// whether it was written.
pub fn write(config: &Config) -> Result<(PathBuf, bool)> {
    let k = Knowledge::open(config);
    let text = render(&lookup::accepted_files(&k)?, &config.knowledge_extra());
    let path = k.dir.join(INDEX_FILE);
    if std::fs::read_to_string(&path).is_ok_and(|old| old == text) {
        return Ok((path, false));
    }
    std::fs::create_dir_all(&k.dir)?;
    crate::fs::write_atomic(&path, text.as_bytes())?;
    Ok((path, true))
}

/// [`write`], a failure reported rather than returned: the index follows
/// a decision already recorded and must never undo or fail it.
pub fn refresh(config: &Config) {
    if let Err(e) = write(config) {
        eprintln!("warning: {INDEX_FILE} not updated: {e:#}");
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::knowledge::lookup::tests::{accept, repo_with_code, DOMAIN_BODY};

    fn config_at(root: &std::path::Path, extra: &str) -> Config {
        let yaml = format!(
            "project:\n  name: p\n  test_command: \"true\"\nknowledge:\n  extra: {extra}\n"
        );
        let mut cfg: Config = serde_yaml::from_str(&yaml).unwrap();
        cfg.config_file = root.join(".zforge").join("config.yaml");
        cfg
    }

    #[test]
    fn short_title_takes_the_first_sentence_and_cuts_at_a_word() {
        assert_eq!(
            short_title("A **refresh** token is single-use."),
            "A refresh token is single-use"
        );
        assert_eq!(
            short_title("Short one. Then a much longer second sentence follows here."),
            "Short one"
        );
        let long = short_title(
            "Every outbound payment request is signed with the merchant key and retried three times",
        );
        assert!(long.ends_with('…'), "{long}");
        assert!(long.chars().count() <= TITLE_CHARS + 1, "{long}");
        assert!(
            "Every outbound payment request is signed with the merchant key"
                .starts_with(long.trim_end_matches('…')),
            "cut at a word: {long}"
        );
    }

    #[test]
    fn index_lists_accepted_items_by_file_and_section_and_skips_drafts() {
        let tmp = tempfile::tempdir().unwrap();
        let root = tmp.path();
        let pinned = repo_with_code(root);
        let cfg = config_at(root, "[]");
        let k = Knowledge::open(&cfg);
        accept(
            root,
            &k,
            "domain.md",
            &format!("---\npinned: {pinned}\n---\n# Domain\n\n{DOMAIN_BODY}"),
        );
        // A draft added after acceptance is not indexed.
        let draft = std::fs::read_to_string(k.dir.join("domain.md"))
            .unwrap()
            .replace(
                "## Open questions",
                "- DOM-009: drafted only. (src/auth/token.rs:1)\n\n## Open questions",
            );
        std::fs::write(k.dir.join("domain.md"), draft).unwrap();

        let (path, written) = write(&cfg).unwrap();
        assert!(written);
        let text = std::fs::read_to_string(&path).unwrap();
        assert!(text.contains("## domain.md (rev 1, 3 items)\n"), "{text}");
        let billing = text.find("### billing\n").expect(&text);
        let dom1 = text
            .find("- DOM-001: An invoice is immutable once issued…\n")
            .expect(&text);
        let auth = text.find("### auth\n").expect(&text);
        let dom3 = text
            .find("- DOM-003: A refresh token is single-use\n")
            .expect(&text);
        assert!(billing < dom1 && dom1 < auth && auth < dom3, "{text}");
        assert!(!text.contains("DOM-009"), "{text}");
        assert!(
            text.contains("## conventions.md — not accepted yet"),
            "{text}"
        );
        assert!(!text.contains("## Reference docs"), "{text}");

        // Unchanged → not rewritten.
        assert!(!write(&cfg).unwrap().1);
    }

    #[test]
    fn index_is_out_of_the_reviewed_files() {
        assert!(crate::knowledge::validate_file(INDEX_FILE).is_err());
    }

    #[test]
    fn index_stays_a_small_fraction_of_the_files_it_indexes() {
        // Items of ~430 bytes, a little under the ~470 bytes per item of a
        // measured 248 KB domain.md (where the same lines come to ~10.5%).
        let mut text = String::from("---\npinned: abc\n---\n# Domain\n");
        for m in 0..20 {
            text.push_str(&format!("\n## services/module-{m}\n\n"));
            for i in 0..25 {
                text.push_str(&format!(
                    "- DOM-{:03}: When an order in module {m} moves to the settled state the \
                     ledger entry is posted exactly once and the outbox event is written in \
                     the same transaction; a retry after a crash finds the entry by its \
                     idempotency key and does nothing, so duplicate postings cannot happen \
                     even under concurrent consumers or a replayed message from the broker. (services/module-{m}/ledger/post.go:10-42, \
                     services/module-{m}/ledger/post_test.go:88)\n",
                    m * 25 + i
                ));
            }
        }
        let accepted = vec![AcceptedFile {
            file: "domain.md".into(),
            revision: 1,
            text: text.clone(),
        }];
        let index = render(&accepted, &[]);
        let ratio = index.len() as f64 / text.len() as f64;
        assert!(ratio <= 0.12, "index is {:.0}% of domain.md", ratio * 100.0);
    }

    #[test]
    fn index_lists_reference_docs_when_configured() {
        let tmp = tempfile::tempdir().unwrap();
        let root = tmp.path();
        let docs = root.join("documents");
        std::fs::create_dir_all(&docs).unwrap();
        std::fs::write(docs.join("README.md"), "# Team docs\n").unwrap();
        let cfg = config_at(root, "[documents]");
        let (path, _) = write(&cfg).unwrap();
        let text = std::fs::read_to_string(path).unwrap();
        assert!(text.contains("## Reference docs"), "{text}");
        assert!(
            text.contains("- documents/README.md — Team docs (entry point)\n"),
            "{text}"
        );
    }
}
